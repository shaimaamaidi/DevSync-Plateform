"""
Domain DTOs for backlog structure with identified tasks.

This module defines Data Transfer Objects (DTOs) used to represent a hierarchical backlog structure
where tasks are enriched with identifiers for tracking, estimation, and sprint planning.

Main classes:
    UserStoryWithIdentifiedTasks,
    EpicBacklogWithIdentifiedTasks,
    BacklogStructureWithIdentifiedTasks
"""

from typing import List
from pydantic import BaseModel

from backend.src.domain.entities.backlog.epic import Epic
from backend.src.domain.entities.backlog.task import IdentifiedTask
from backend.src.domain.entities.backlog.user_story import UserStory


class UserStoryWithIdentifiedTasks(BaseModel):
    """
    User story enriched with identified tasks.

    This DTO represents a functional requirement decomposed into traceable and identifiable tasks,
    enabling estimation, planning, and tracking.

    Attributes:
        user_story: The user story representing a functional requirement.
        tasks: List of identified tasks linked to the user story.
    """
    user_story: UserStory
    tasks: List[IdentifiedTask]

class EpicBacklogWithIdentifiedTasks(BaseModel):
    """
    Epic representation containing user stories with identified tasks.

    This DTO groups user stories under a high-level business objective,
    where each user story contains identifiable and traceable tasks.

    Attributes:
        epic: The epic entity representing a high-level feature or goal.
        user_stories: List of user stories with identified tasks.
    """
    epic: Epic
    user_stories: List[UserStoryWithIdentifiedTasks]

class BacklogStructureWithIdentifiedTasks(BaseModel):
    """
    Complete backlog structure with identified tasks.

    This represents the full hierarchical backlog generated by the system,
    including epics, user stories, and traceable tasks.

    Attributes:
        epics: List of epics composing the backlog.
    """
    epics: List[EpicBacklogWithIdentifiedTasks] = []