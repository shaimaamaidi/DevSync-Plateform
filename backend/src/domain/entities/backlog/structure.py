"""
Domain DTOs for backlog structure representation.

This module defines Data Transfer Objects (DTOs) used to represent a hierarchical backlog structure,
including epics, user stories, and tasks. It is used for organizing and transferring structured backlog data
between layers of the application.

Main classes:
    UserStoryWithTasks, EpicBacklog, BacklogStructure
"""

from pydantic import BaseModel
from typing import List

from backend.src.domain.entities.backlog.epic import Epic
from backend.src.domain.entities.backlog.task import Task
from backend.src.domain.entities.backlog.user_story import UserStory


class UserStoryWithTasks(BaseModel):
    """
    User story enriched with its associated tasks.

    Attributes:
        user_story: User story entity representing a functional requirement.
        tasks: List of tasks linked to the user story.
    """
    user_story: UserStory
    tasks: List[Task]

class EpicBacklog(BaseModel):
    """
    Epic representation containing grouped user stories.

    Attributes:
        epic: Epic entity representing a high-level feature or business goal.
        user_stories: List of user stories belonging to the epic.
    """
    epic: Epic
    user_stories: List[UserStoryWithTasks]

class BacklogStructure(BaseModel):
    """
    Complete backlog structure composed of multiple epics.

    This object represents the full hierarchical backlog generated by the system,
    including epics, their user stories, and associated tasks.

    Attributes:
        epics: List of epics composing the backlog.
    """
    epics: List[EpicBacklog] =[]