"""
Domain DTO for generated task representation.

This module defines the Data Transfer Object (DTO) used to represent
tasks generated by the AI system. A generated task contains metadata
such as title, description, assignee, priority, status, and target
location within the project structure.

Main classes:
    BaseGeneratedTask
"""

from pydantic import BaseModel


class BaseGeneratedTask(BaseModel):
    """
    Representation of a generated task.

    This DTO represents a task generated by an LLM, including its metadata
    such as description, assignment, priority, status, and target location
    within the project structure.

    Attributes:
        task_name: Name or title of the task.
        task_description: Detailed description of the task.
        task_assigne: Name of the task assignee.
        task_status: Status assigned to the task.
        task_priority: Priority level assigned to the task.
        location: Target location where the task should be created.
    """
    task_name: str
    task_description: str
    task_assigne: str
    task_status: str
    task_priority: str
    location: str